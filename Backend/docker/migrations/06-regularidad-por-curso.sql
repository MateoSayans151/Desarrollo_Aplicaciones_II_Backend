-- Crea la configuracion de regularidad por curso y completa los cursos existentes.
-- Los valores 75% y 6.0 preservan los valores iniciales que usaba el frontend.
BEGIN;

CREATE TABLE IF NOT EXISTS regularidades_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL,
    codigo VARCHAR(30) NOT NULL,
    asistencia_minima NUMERIC(5, 2) NOT NULL,
    promedio_minimo NUMERIC(4, 2) NOT NULL,
    CONSTRAINT uk_regularidad_curso UNIQUE (curso_id),
    CONSTRAINT fk_regularidad_curso FOREIGN KEY (curso_id) REFERENCES cursos(id) ON DELETE CASCADE,
    CONSTRAINT ck_regularidad_asistencia CHECK (asistencia_minima BETWEEN 0 AND 100),
    CONSTRAINT ck_regularidad_promedio CHECK (promedio_minimo BETWEEN 0 AND 10)
);

INSERT INTO regularidades_curso (curso_id, codigo, asistencia_minima, promedio_minimo)
SELECT c.id, c.codigo, 75.00, 6.00
FROM cursos c
WHERE NOT EXISTS (
    SELECT 1 FROM regularidades_curso r WHERE r.curso_id = c.id
);

UPDATE regularidades_curso r
SET codigo = c.codigo
FROM cursos c
WHERE c.id = r.curso_id AND r.codigo IS DISTINCT FROM c.codigo;

COMMIT;
